import { PASSWORD_LENGTH } from "@/app/constants";

const TWO_BYTE_CHARACTER = "á";
const BYTES_PER_TWO_BYTE_CHARACTER = 2;

export const CURRENT_PASSWORD_AT_MAX_LENGTH = "a".repeat(
  PASSWORD_LENGTH.MAX
);

export const CURRENT_PASSWORD_AT_MAX_BYTES =
  TWO_BYTE_CHARACTER.repeat(
    PASSWORD_LENGTH.MAX_BYTES / BYTES_PER_TWO_BYTE_CHARACTER
  );

export const CURRENT_PASSWORD_ONE_BYTE_ABOVE_MAX =
  `${CURRENT_PASSWORD_AT_MAX_BYTES  }a`;

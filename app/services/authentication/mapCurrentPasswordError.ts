import type { AuthError } from "@supabase/supabase-js";
import {
  PASSWORD_CHANGE_ERROR_CODE,
  SIGN_IN_ERROR_CODE,
  type PasswordChangeErrorCode,
  type SignInErrorCode,
} from "@/app/constants";
import { createPasswordChangeError } from "@/app/utils/password-change/createPasswordChangeError";
import type { PasswordChangeError } from "@/app/utils/password-change/models/PasswordChangeError.interface";
import { mapSignInAuthError } from "./mapSignInAuthError";

const CURRENT_PASSWORD_ERROR_CODE: Record<
  SignInErrorCode,
  PasswordChangeErrorCode
> = {
  [SIGN_IN_ERROR_CODE.ACCOUNT_BLOCKED_BY_ADMINISTRATION]:
    PASSWORD_CHANGE_ERROR_CODE.ACCOUNT_BLOCKED_BY_ADMINISTRATION,
  [SIGN_IN_ERROR_CODE.ACCOUNT_BLOCKED_BY_ATTEMPTS]:
    PASSWORD_CHANGE_ERROR_CODE.ACCOUNT_BLOCKED_BY_ATTEMPTS,
  [SIGN_IN_ERROR_CODE.ACCOUNT_RECOVERY_REQUIRED]:
    PASSWORD_CHANGE_ERROR_CODE.ACCOUNT_RECOVERY_REQUIRED,
  [SIGN_IN_ERROR_CODE.INVALID_CREDENTIALS]:
    PASSWORD_CHANGE_ERROR_CODE.CURRENT_PASSWORD_INVALID,
  [SIGN_IN_ERROR_CODE.NETWORK]:
    PASSWORD_CHANGE_ERROR_CODE.NETWORK,
  [SIGN_IN_ERROR_CODE.PASSWORD_REQUIRED]:
    PASSWORD_CHANGE_ERROR_CODE.UNKNOWN,
  [SIGN_IN_ERROR_CODE.PASSWORD_TOO_LONG]:
    PASSWORD_CHANGE_ERROR_CODE.UNKNOWN,
  [SIGN_IN_ERROR_CODE.SESSION_INACTIVE]:
    PASSWORD_CHANGE_ERROR_CODE.SESSION_INACTIVE,
  [SIGN_IN_ERROR_CODE.TOO_MANY_REQUESTS]:
    PASSWORD_CHANGE_ERROR_CODE.TOO_MANY_REQUESTS,
  [SIGN_IN_ERROR_CODE.UNKNOWN]:
    PASSWORD_CHANGE_ERROR_CODE.UNKNOWN,
  [SIGN_IN_ERROR_CODE.USERNAME_LENGTH]:
    PASSWORD_CHANGE_ERROR_CODE.UNKNOWN,
  [SIGN_IN_ERROR_CODE.USERNAME_REQUIRED]:
    PASSWORD_CHANGE_ERROR_CODE.UNKNOWN,
};

export const mapCurrentPasswordError = (
  error: AuthError
): PasswordChangeError =>
  createPasswordChangeError(
    CURRENT_PASSWORD_ERROR_CODE[
      mapSignInAuthError(error).code
    ]
  );
